/**
 * Yidhan theme system.
 *
 * Two themes, Light and Dark. The stored theme values are still `light` and `dark`;
 * useAppTheme and public/boot.js choose between them.
 *
 * After changing a theme file, run `npm run theme:generate` to rewrite the generated
 * block in src/index.css. Never edit that block by hand: src/themes/themeCss.test.ts
 * fails when it drifts from the generator's output.
 */

import light from './light';
import dark from './dark';
import { themeToCss, type ThemeConfig } from './types';

export const ACTIVE_LIGHT_THEME = light;
export const ACTIVE_DARK_THEME = dark;

export const allThemes: Record<string, ThemeConfig> = { light, dark };

/** The generated block in src/index.css, markers included. Pure, so a test can compare. */
export function generateThemeBlock(lightTheme: ThemeConfig = light, darkTheme: ThemeConfig = dark): string {
  return `/* THEME-START - Generated by npm run theme:generate */
/* Light Theme: ${lightTheme.displayName} - ${lightTheme.description} */
:root {
${themeToCss(lightTheme.colors)}
}

/* Dark Theme: ${darkTheme.displayName} - ${darkTheme.description} */
[data-theme="dark"] {
${themeToCss(darkTheme.colors)}
}
/* THEME-END */`;
}

/** Matches the generated block in src/index.css. */
export const THEME_BLOCK_PATTERN = /\/\* THEME-START[\s\S]*?THEME-END \*\//;

export { themeToCss, paperGrain, GRAIN_TILE_PX, type ThemeConfig, type ThemeColors } from './types';
